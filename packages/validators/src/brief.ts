import { formatLadder } from './format';
import { handoverFile, handoverSection } from './handover';
import type { JournalRow } from './journal';
import type { LadderReport } from './ladder';

/** Where the static executor instruction lives, from the repository root. */
export const EXECUTOR_FILE = 'validators/EXECUTOR.md';

export type BriefInput = {
  component: string;
  /** The static instruction, the text of validators/EXECUTOR.md. */
  executor: string;
  /** A live run of the validator on the brief's seeds. */
  report: LadderReport;
  floor: number;
  last: JournalRow | undefined;
  /** The text of HANDOVER.md, or undefined when there is none. */
  handover: string | undefined;
  /** The commit the run was made at, or undefined outside a repository. */
  head: string | undefined;
  /** True for the handover test: the handover's hypotheses (and the last row's) are left out. */
  fresh: boolean;
};

/**
 * The instruction an executor session starts from: the live state (the ladder on the brief's seeds with the
 * first failing level's items and the floor, the last journal row, the handover's next actions and, unless
 * fresh, its hypotheses), then validators/EXECUTOR.md with the component filled in.
 */
export function composeBrief(input: BriefInput): string {
  const { component } = input;
  const at = input.head ? `commit ${input.head.slice(0, 12)}` : 'no commit (outside a repository)';
  const parts: string[] = [];
  parts.push(`# Brief: validator ${component}${input.fresh ? ' (fresh)' : ''}`);
  parts.push(
    `Generated by \`driftbench validate ${component} --brief${input.fresh ? ' --fresh' : ''}\` at ${at}. The live state comes first; the static instruction follows it.`,
  );
  if (input.fresh) {
    parts.push(
      "Fresh brief: the handover's hypotheses and the last row's hypothesis are left out. Reproduce the level from the files alone (the handover test, docs/validators.md section 10.4).",
    );
  }
  parts.push('## Live state: the ladder');
  parts.push(fence(formatLadder(input.report, { floor: input.floor }).trimEnd(), ''));
  parts.push('## Last journal row');
  if (input.last) {
    const row: Partial<JournalRow> = { ...input.last };
    if (input.fresh) delete row.hypothesis;
    parts.push(fence(JSON.stringify(row, null, 2), 'json'));
  } else {
    parts.push('The journal is empty: this is the first iteration.');
  }
  const handover = input.handover;
  parts.push(`## Next actions (from ${handoverFile(component)})`);
  if (handover === undefined) {
    parts.push(`${handoverFile(component)} does not exist yet: write it at the end of this iteration.`);
  } else {
    parts.push(handoverSection(handover, 'Next actions') || '(the section is empty)');
    if (!input.fresh) {
      parts.push(`## Hypotheses tried (from ${handoverFile(component)})`);
      parts.push(handoverSection(handover, 'Hypotheses tried') || '(the section is empty)');
    }
  }
  parts.push('---');
  parts.push(input.executor.replaceAll('<component>', component).trimEnd());
  return `${parts.join('\n\n')}\n`;
}

function fence(text: string, language: string): string {
  return `\`\`\`${language}\n${text}\n\`\`\``;
}
