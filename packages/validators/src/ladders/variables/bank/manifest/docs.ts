/** `docs/variables.md#planner-rules R9` for each rule a stem cites. */
export function docAnchors(stemId: string): string[] {
  return (DOC_RULES[stemId] ?? []).map((rule) => {
    const rank = /^R\d+$/.test(rule) ? ` ${rule}` : '';
    return `docs/variables.md#${DOC_SECTION[rule]}${rank}`;
  });
}
