/**
 * Generation quality on the Northwind fixture's generated suite (seed-free, judged once):
 *
 * gen.task: the first ask of every complete spec asks, exactly, for the act the spec carries (judgeAsk): a code
 * ask is set off in the fake agent for the atom `askFrom` names, by a text of the grammar generated by code from
 * the approved map (ask-grammar.ts); a bank ask is a phrase of its situation; a recorded session's ask is the
 * session's own message; a neutral ask is a fixed row. An ask that carries no act sets off none of the row's atoms.
 * No word of an ask is read here. One item per test type.
 *
 * gen.reads: no complete spec expects a Read of a file the estate lacks. One item per test type.
 *
 * gen.coverage: at least one complete spec names every atom of a kind (one item per atom kind); every domain
 * rule of a skill has a judged criterion in a complete spec (one item per skill and the standing rules); no
 * spec carries the gap markers the bench run left (one item per marker).
 */

