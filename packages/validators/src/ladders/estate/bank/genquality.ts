function firstAsk(spec: FixtureSuite['specs'][number]): string | undefined {
  const block = (spec.spec.blocks ?? [])[0] as { when?: { user?: string } } | undefined;
  return block?.when?.user;
}

function readsOf(spec: FixtureSuite['specs'][number]): string[] {
  const out: string[] = [];
  for (const block of (spec.spec.blocks ?? []) as Array<{ expect?: { tools?: unknown[] } }>) {
    for (const tool of (block.expect?.tools ?? []) as Array<{
      label?: string;
      input?: Record<string, unknown>;
    }>) {
      if (tool.label !== 'Read') continue;
      const path = tool.input?.file_path as { contains?: string; equals?: string } | string | undefined;
      const value = typeof path === 'string' ? path : (path?.contains ?? path?.equals);
      if (typeof value === 'string' && value !== '') out.push(value);
    }
  }
  return out;
}

let fixtureFiles: string[] | undefined;
function filesOfFixture(): string[] {
  fixtureFiles ??= (
    readdirSync(FIXTURE, { recursive: true, withFileTypes: true }) as Array<{
      isFile(): boolean;
      parentPath: string;
      name: string;
    }>
  )
    .filter((entry) => entry.isFile())
    .map((entry) => relative(FIXTURE, join(entry.parentPath, entry.name)));
  return fixtureFiles;
}

function seedFreeFamily(
  id: string,
  level: number,
  component: string,
  specs: Array<{
    key: string;
    tier: Tier;
    title: string;
    cause: string;
    component?: string;
    judge(suite: FixtureSuite): Promise<ItemResult> | ItemResult;
  }>,
): Family {
  const items = itemsOf(
    id,
    level,
    component,
    specs.map(({ key, tier, title, cause, component: own }) => ({
      key,
      tier,
      title,
      cause,
      ...(own ? { component: own } : {}),
    })),
  );
  return {
    id,
    level,
    component,
    items,
    seedFree: true,
    async evaluate() {
      const suite = await fixtureSuite();
      const out = new Map<string, ItemResult>();
      for (const spec of specs) {
        try {
          out.set(`${id}.${spec.key}`, await spec.judge(suite));
        } catch (cause) {
          out.set(`${id}.${spec.key}`, {
            pass: false,
            detail: `the item threw: ${cause instanceof Error ? cause.message : String(cause)}`,
          });
        }
      }
      return out;
    },
  };
}

const ofType = (suite: FixtureSuite, type: string) =>
  suite.specs.filter((spec) => spec.complete && spec.testType === type);

/** The most specs a failure detail lists by id and ask; the rest are counted. */
const LISTED = 50;

/**
 * What the fake sets off for an ask (atom ids, from its own dispatch), and the template of the grammar the ask is
 * built from with the atoms of its acts (undefined when it fits none).
 */
export type Fake = {
  setOff: (ask: string) => string[];
  match: (ask: string) => { kind: string; atoms: string[] } | undefined;
};

const fakeOf = new WeakMap<FixtureSuite, Promise<Fake>>();

/**
 * The fake's dispatch for a suite: the approved map and the phrase bank beside it, and the grammar generated by
 * code from that map, written to a folder of its own.
 */
export function fakeDispatch(suite: FixtureSuite): Promise<Fake> {
  let found = fakeOf.get(suite);
  if (!found) {
    found = (async () => {
      const map = await loadEstateMap(suite.map);
      if (!map.ok) throw new Error('the map does not load');
      const grammar = askGrammar(map.map.atoms as unknown as MapAtom[]);
      const folder = mkdtempSync(join(tmpdir(), 'estate-ask-grammar-'));
      const path = join(folder, 'grammar.json');
      writeFileSync(path, JSON.stringify(grammar));
      const fake = (await import(pathToFileURL(join(FIXTURE, 'live/fake/dispatch.mjs')).href)) as {
        loadDispatch(env: Record<string, string>): unknown;
        setOff(index: unknown, ask: string): { atoms: Array<{ id: string }> };
        matchAsk(grammar: unknown, ask: string): { kind: string; atoms: string[] } | undefined;
      };
      const phrases = besideOrFixture(suite, 'phrases.yaml');
      const env = { FAKE_MAP: suite.map, FAKE_PHRASES: phrases, FAKE_GRAMMAR: path };
      const index = fake.loadDispatch(env);
      const given = (index as { grammar?: unknown } | undefined)?.grammar;
      return {
        setOff: (ask: string) => fake.setOff(index, ask).atoms.map((atom) => atom.id),
        match: (ask: string) => fake.matchAsk(given, ask),
      };
    })();
    fakeOf.set(suite, found);
  }
  return found;
}

/** A file beside the suite's map, or the fixture's own when the suite has none. */
function besideOrFixture(suite: FixtureSuite, name: string): string {
  const beside = join(suite.work, name);
  return existsSync(beside) ? beside : join(FIXTURE, name);
}

type Situation = { use: string; atoms: string[]; phrases: string[] };

/** The situations of the phrase bank beside the suite, by id: their use, the atoms they set off, their phrases. */
function situationsOf(suite: FixtureSuite): Map<string, Situation> {
  const bank = parse(readFileSync(besideOrFixture(suite, 'phrases.yaml'), 'utf8')) as {
    situations?: Array<{ id?: string; use?: string; atoms?: string[]; phrases?: Array<{ text?: string }> }>;
  };
  return new Map(
    (bank.situations ?? []).map((situation) => [
      String(situation.id),
      {
        use: String(situation.use),
        atoms: situation.atoms ?? [],
        phrases: (situation.phrases ?? []).map((phrase) => String(phrase.text)),
      },
    ]),
  );
}

/** The user messages of a recorded session beside the suite, in order. */
function sessionAsks(suite: FixtureSuite, name: string): string[] {
  const path = besideOrFixture(suite, join('sessions', `${name}.jsonl`));
  if (!existsSync(path)) return [];
  const asks: string[] = [];
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    if (line.trim() === '') continue;
    const record = JSON.parse(line) as { type?: unknown; message?: { role?: unknown; content?: unknown } };
    const content = record.message?.content;
    if (record.type === 'user' && typeof content === 'string') asks.push(content);
  }
  return asks;
}

type Judged = { why?: string };

/**
 * Why the first ask of a spec does not ask for the act it carries, or nothing when it does:
 * - a code-written ask names its act atom in `askFrom`; that atom declares an act in the map and the fake sets it
 *   off on the ask. A row just outside the trigger or a near miss asks for no act: its ask is a `fixed` row or a
 *   `hypothetical` text of the grammar about one of the row's atoms, and a hypothetical text never counts as the act;
 * - a neutral code ask (`askFrom: neutral`) is a `fixed` row of section 5, byte for byte;
 * - a bank ask is a phrase of its situation, byte for byte; its act is the situation's atoms, none for a situation
 *   just outside the trigger or a near miss;
 * - a recorded session's ask is the session's own message at the block the spec replays from; its act is the row.
 * An ask that carries no act sets off none of the row's atoms.
 */
type PlanRow = { id: string; atomIds: string[]; testType: string };

/** The rows of the approved plan beside the suite, by id: the validator's input, never the spec's own word. */
function planRowsOf(suite: FixtureSuite): Map<string, PlanRow> {
  const plan = parse(readFileSync(besideOrFixture(suite, 'plan.yaml'), 'utf8')) as { rows?: PlanRow[] };
  return new Map((plan.rows ?? []).map((row) => [row.id, row]));
}

function judgeAsk(
  spec: FixtureSuite['specs'][number],
  fake: Fake,
  situations: ReadonlyMap<string, Situation>,
  byId: ReadonlyMap<string, MapAtom>,
  suite: FixtureSuite,
  rows: ReadonlyMap<string, PlanRow>,
): Judged {
  const ask = firstAsk(spec);
  if (ask === undefined || ask === '') return { why: 'it has no first ask' };
  type Meta = { ask?: unknown; askFrom?: unknown; situation?: unknown; session?: unknown; planRow?: unknown };
  const meta = (spec.spec.metadata?.estate ?? {}) as Meta;
  // The row comes from the approved plan, and the atoms an ask may cite from the map (ask-binding.ts): never from
  // the atoms the spec lists about itself.
  const row = typeof meta.planRow === 'string' ? rows.get(meta.planRow) : undefined;
  if (!row || row.testType !== spec.testType) return { why: 'it names no row of the plan of its test type' };
  const rowAtoms = row.atomIds;
  const sources = rowSources(rowAtoms, byId);
  const replay = (spec.spec.metadata as { replay?: { from_block?: unknown } } | undefined)?.replay;
  const fired = fake.setOff(ask);
  // docs/estate.md section 5: a row just outside the trigger, or a near miss, asks for no act.
  const use = USE_OF_TEST[spec.testType] ?? 'trigger';
  const noAct = use === 'outside' || use === 'near_miss';
  const none = (): Judged => {
    const hit = fired.filter((id) => rowAtoms.includes(id));
    return hit.length > 0 ? { why: `it carries no act and sets off ${hit[0]}` } : {};
  };
  const acts = (act: readonly string[]): Judged => {
    const missing = act.find((id) => !byId.has(id));
    if (missing) return { why: `its act ${missing} is no atom of the map` };
    if (!act.some((id) => sources.has(id))) return { why: `its act ${act[0]} is no source of its row` };
    return act.some((id) => fired.includes(id)) ? {} : { why: `the fake does not set off its act ${act[0]}` };
  };
  // The first block's own source decides: an approved phrase of the spec's situation is a bank ask, whatever
  // other blocks of the spec were written by code (askBuild is null for such a block).
  const banked = typeof meta.situation === 'string' ? situations.get(meta.situation) : undefined;
  if (meta.ask === 'bank' || (banked !== undefined && banked.phrases.includes(ask))) {
    if (!banked) return { why: 'it names no situation of the bank' };
    if (!banked.phrases.includes(ask)) return { why: `the ask is no phrase of ${String(meta.situation)}` };
    const outside = banked.use === 'outside' || banked.use === 'near_miss';
    if (outside !== noAct) return { why: `the situation ${String(meta.situation)} is of use ${banked.use}` };
    return outside ? none() : acts(banked.atoms);
  }
  if (meta.ask === 'code') {
    if (typeof meta.askFrom !== 'string' || meta.askFrom === '') return { why: 'it carries no act' };
    if (meta.askFrom === 'neutral') {
      const fixed = ASK_TEMPLATES.some((row) => row.kind === 'fixed' && row.template === ask);
      return fixed ? none() : { why: 'a neutral ask that is no fixed row of section 5' };
    }
    const matched = fake.match(ask);
    if (matched?.kind === 'hypothetical') {
      // A hypothetical row asks what an act would mean: it is the ask of a row that asks for no act, about one of
      // the row's atoms, and it never counts as the act.
      if (!noAct) return { why: 'a hypothetical ask carries no act, and the row asks for one' };
      // About a source of the row: its atoms, or one a row atom's fields name (the rule a guard enforces).
      if (!matched.atoms.some((id) => sources.has(id)))
        return { why: 'a hypothetical ask about no atom of the row' };
      return none();
    }
    if (noAct) return { why: `the row asks for no act, and the ask is no hypothetical or fixed row` };
    const id = meta.askFrom.split(' ')[0] as string;
    const atom = byId.get(id);
    if (!atom) return { why: `its act ${id} is no atom of the map` };
    if (declaredActs(atom).length === 0) return { why: `its act ${id} declares no act text in the map` };
    return acts([id]);
  }
  if (meta.ask === 'session') {
    if (typeof meta.session !== 'string') return { why: 'it names no recorded session' };
    const from = typeof replay?.from_block === 'number' ? replay.from_block : 0;
    if (sessionAsks(suite, meta.session)[from] !== ask)
      return { why: `the ask is not the message of session ${meta.session} at block ${from}` };
    return rowAtoms.length > 0 ? {} : { why: 'it carries no act' };
  }
  return { why: 'it carries no act' };
}

/**
 * The complete specs of a suite whose first ask carries an act the fake does not set off, with the reason: the
 * coverage check of the generated grammar (every span source the product may use is in it).
 */
export async function unsetAsks(
  suite: FixtureSuite,
): Promise<Array<{ id: string; ask: string; why: string }>> {
  const map = await loadEstateMap(suite.map);
  if (!map.ok) throw new Error('the map does not load');
  const byId = new Map((map.map.atoms as unknown as MapAtom[]).map((atom) => [atom.id, atom]));
  const fake = await fakeDispatch(suite);
  const situations = situationsOf(suite);
  const rows = planRowsOf(suite);
  const out: Array<{ id: string; ask: string; why: string }> = [];
  for (const spec of suite.specs.filter((one) => one.complete)) {
    const { why } = judgeAsk(spec, fake, situations, byId, suite, rows);
    if (why?.startsWith('the fake does not set off'))
      out.push({ id: spec.id, ask: firstAsk(spec) ?? '', why });
  }
  return out;
}

export function taskFamily(): Family {
  return seedFreeFamily(
    'gen.task',
    4,
    GENERATE,
    TEST_TYPES.map((type) => ({
      key: type,
      tier: 2 as Tier,
      title: `the first ask of every complete ${type} spec asks, exactly, for the act the spec carries`,
      cause: 'ask for the act of the row, in a text the fake sets off for that act and no other',
      async judge(suite) {
        const specs = ofType(suite, type);
        if (specs.length === 0) return { pass: false, detail: `no complete ${type} spec` };
        const map = await loadEstateMap(suite.map);
        if (!map.ok) return { pass: false, detail: 'the map does not load' };
        const byId = new Map((map.map.atoms as unknown as MapAtom[]).map((atom) => [atom.id, atom]));
        const fake = await fakeDispatch(suite);
        const situations = situationsOf(suite);
        const rows = planRowsOf(suite);
        const bad: Array<[FixtureSuite['specs'][number], string]> = [];
        for (const spec of specs) {
          const { why } = judgeAsk(spec, fake, situations, byId, suite, rows);
          if (why) bad.push([spec, why]);
        }
        return bad.length === 0
          ? { pass: true, detail: `holds (${specs.length})` }
          : {
              pass: false,
              detail: `${bad.length} of ${specs.length} asks do not ask for their act: ${bad
                .slice(0, LISTED)
                .map(([spec, why]) => `${spec.id} ("${firstAsk(spec)}": ${why})`)
                .join('; ')}${bad.length > LISTED ? `; and ${bad.length - LISTED} more` : ''}`,
            };
      },
    })),
  );
}

export function readsFamily(): Family {
  return seedFreeFamily(
    'gen.reads',
    4,
    THEN,
    TEST_TYPES.map((type) => ({
      key: type,
      tier: 2 as Tier,
      title: `no complete ${type} spec expects a Read of a file the estate lacks`,
      cause: 'expect a Read only of a file the estate holds',
      judge(suite) {
        const files = filesOfFixture();
        const specs = ofType(suite, type);
        if (specs.length === 0) return { pass: false, detail: `no complete ${type} spec` };
        for (const spec of specs) {
          for (const read of readsOf(spec)) {
            const clean = read.replace(/^\.\//, '');
            if (!existsSync(join(FIXTURE, clean)) && !files.some((file) => file.endsWith(clean)))
              return { pass: false, detail: `${spec.id} expects a Read of ${read}, which the estate lacks` };
          }
        }
        return { pass: true, detail: `holds (${specs.length})` };
      },
    })),
  );
}

const FOCUS_KINDS: Array<[string, Tier]> = [
  ['instruction', 2],
  ['gate', 2],
  ['reference', 3],
  ['route', 1],
  ['skill', 2],
  ['script', 3],
  ['subagent', 3],
  ['guard', 3],
  ['tool', 3],
  ['register', 3],
  ['stage', 3],
  ['hazard', 4],
  ['setting', 4],
  ['invariant', 4],
];
/** docs/estate.md section 5 (--focus): the report names the atoms with no complete spec. */
const AT_LEAST = 1;
const SKILLS = ['invoice-reconcile', 'shipment-tracker', 'supplier-email', 'weekly-report', 'standing'];
/** The gap markers and their fix; a fix the generated estates' items already name keeps that cause. */
const MARKERS: Array<[string, string]> = [
  ['needs-ordered-anchor', 'anchor an ordered pair whose ends are no tool label, skill or stage'],
  ['needs-stage-reach-check', 'write a stage reach check'],
  ['needs-guard-timing', 'write a guard timing check'],
  ['needs-guard-message-check', 'write a guard message check'],
  ['needs-recorded-session', 'replay a row from a recorded session the generator finds by itself'],
  ['needs-negation', 'write the inverse of a predicate for a negative control'],
];

export function coverageFamily(): Family {
  return seedFreeFamily('gen.coverage', 4, GENERATE, [
    ...FOCUS_KINDS.map(([kind, tier]) => ({
      key: `one-per-${kind}`,
      tier,
      title: `every ${kind} atom is named by at least ${AT_LEAST} complete spec`,
      cause: `generate a complete spec for every ${kind} atom`,
      async judge(suite: FixtureSuite): Promise<ItemResult> {
        const map = await loadEstateMap(suite.map);
        if (!map.ok) return { pass: false, detail: 'the map does not load' };
        const atoms = map.map.atoms.filter((atom) => atom.kind === kind);
        if (atoms.length === 0) return { pass: false, detail: `the fixture holds no ${kind} atom` };
        // docs/estate.md section 5: a Read of a file the estate copy does not hold cannot succeed. With a registered
        // `some_call` checker the complete specs of that reference check the attempted Read of the exact file with
        // it, never a successful read; with no such checker the reference waits on `needs-existing-file`.
        const waiting = new Set(
          (suite.report.gaps ?? []).find((entry) => entry.marker === 'needs-existing-file')?.atoms ?? [],
        );
        const absent = atoms.filter((atom) => kind === 'reference' && atom.fields?.exists === false);
        if (!suite.checks.includes('some_call')) {
          const unmarked = absent.filter((atom) => !waiting.has(atom.id));
          if (unmarked.length > 0)
            return {
              pass: false,
              detail: `${unmarked.length} of ${absent.length} references to a missing file are not marked needs-existing-file, such as ${unmarked[0]?.id}`,
            };
        } else {
          const unchecked = absent.filter((atom) => {
            const path = String(atom.fields?.path ?? '');
            if (path === '' || waiting.has(atom.id)) return true;
            const name = path.slice(path.lastIndexOf('/') + 1);
            const specs = suite.specs.filter((spec) => spec.complete && spec.atoms.includes(atom.id));
            const attempts = (spec: (typeof specs)[number]) =>
              (
                ((spec.spec.rules?.custom?.some_call as { calls?: unknown } | undefined)?.calls ??
                  []) as Array<{
                  label?: unknown;
                  input?: { file_path?: { contains?: unknown } };
                  count?: unknown;
                }>
              ).filter((call) => call.label === 'Read' && call.input?.file_path?.contains === path);
            const reads = (spec: (typeof specs)[number]) =>
              (spec.spec.blocks ?? [])
                .flatMap((block) => block.expect?.references ?? [])
                .some((ref) => String((ref as { path?: unknown }).path ?? '').includes(name));
            return (
              specs.length === 0 ||
              !specs.every((spec) => attempts(spec).length > 0 && !reads(spec)) ||
              !specs.some((spec) =>
                attempts(spec).some((call) => {
                  const min = (call.count as { min?: unknown } | undefined)?.min;
                  return typeof min === 'number' && min >= 1;
                }),
              )
            );
          });
          if (unchecked.length > 0)
            return {
              pass: false,
              detail: `${unchecked.length} of ${absent.length} references to a missing file have no complete spec that checks the attempted Read with some_call, such as ${unchecked[0]?.id}`,
            };
        }
        const short = atoms
          .filter((atom) => !absent.includes(atom))
          .map(
            (atom) =>
              [
                atom.id,
                suite.specs.filter((spec) => spec.complete && spec.atoms.includes(atom.id)).length,
              ] as const,
          )
          .filter(([, count]) => count < AT_LEAST);
        return short.length === 0
          ? { pass: true, detail: 'holds' }
          : {
              pass: false,
              detail: `${short.length} of ${atoms.length} ${kind} atoms have fewer than ${AT_LEAST} complete specs, such as ${short[0]?.[0]} with ${short[0]?.[1]}`,
            };
      },
    })),
    ...SKILLS.map((skill) => ({
      key: `judged-${skill}`,
      tier: 3 as Tier,
      title: `every domain rule of ${skill} has a judged criterion in a complete spec`,
      cause: 'judge every domain rule no code checks with a criterion from its own words',
      component: THEN,
      async judge(suite: FixtureSuite): Promise<ItemResult> {
        const map = await loadEstateMap(suite.map);
        if (!map.ok) return { pass: false, detail: 'the map does not load' };
        const rules = map.map.atoms.filter(
          (atom) =>
            atom.kind === 'instruction' &&
            atom.id.startsWith(`instruction.${skill}.`) &&
            atom.evidence.some((item) => item.type === 'custom'),
        );
        if (rules.length === 0) return { pass: true, detail: 'no domain rule here' };
        const unjudged = rules.filter(
          (rule) =>
            !suite.specs.some(
              (spec) =>
                spec.complete &&
                ((spec.spec.blocks ?? []) as Array<{ expect?: { criteria?: unknown[] } }>).some((block) =>
                  (block.expect?.criteria ?? []).some((criterion) =>
                    JSON.stringify(criterion).includes(rule.id),
                  ),
                ),
            ),
        );
        return unjudged.length === 0
          ? { pass: true, detail: `holds (${rules.length})` }
          : {
              pass: false,
              detail: `${unjudged.length} of ${rules.length} domain rules have no judged criterion, such as ${unjudged[0]?.id}`,
            };
      },
    })),
    ...MARKERS.map(([marker, cause]) => ({
      key: marker,
      tier: 4 as Tier,
      title: `no generated spec of the fixture is incomplete for ${marker}`,
      cause,
      component: THEN,
      judge(suite: FixtureSuite): ItemResult {
        const gap = (suite.report.gaps ?? []).find((entry) => entry.marker === marker);
        return !gap || gap.specs === 0
          ? { pass: true, detail: 'holds' }
          : {
              pass: false,
              detail: `${gap.specs} specs are incomplete for ${marker}, such as on ${gap.atoms[0]}`,
            };
      },
    })),
  ]);
}
