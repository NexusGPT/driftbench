/**
 * Generation quality on the Northwind fixture's generated suite (seed-free, judged once):
 *
 * gen.task: the first ask of every complete spec sets off, in the fake agent, the act the spec carries: the atom
 * named by `askFrom` for a code-written ask, the atoms of its situation for a bank phrase. The fake sets an atom off
 * only on a bank phrase, a declared ask, or a text of the grammar generated by code from the approved map
 * (ask-grammar.ts). An ask that carries no act (a neutral one, a situation just outside the trigger) must set off
 * none of the row's atoms. No word of an ask is read here. One item per test type.
 *
 * gen.reads: no complete spec expects a Read of a file the estate lacks. One item per test type.
 *
 * gen.coverage: at least one complete spec names every atom of a kind (one item per atom kind); every domain
 * rule of a skill has a judged criterion in a complete spec (one item per skill and the standing rules); no
 * spec carries the gap markers the bench run left (one item per marker).
 */

const GENERATE = 'packages/generate/src/estate/generate.ts';
const THEN = 'packages/generate/src/estate/then.ts';

const TEST_TYPES = [
  'obligation',
  'outside_trigger',
  'twin',
  'ordered_pair',
  'skip_pressure',
  'route_positive',
  'route_near_miss',
  'misroute',
  'read_when',
  'script_fixture',
  'dispatch',
  'contract_alone',
  'stop_resume',
  'guard_positive',
  'guard_negative',
  'guard_hostile',
  'tool_boundary',
  'tool_denied',
  'stage_order',
  'stage_skip',
  'register_sample',
  'hazard_recovery',
  'journey',
] as const;

function firstAsk(spec: FixtureSuite['specs'][number]): string | undefined {
  const block = (spec.spec.blocks ?? [])[0] as { when?: { user?: string } } | undefined;
  return block?.when?.user;
}

function readsOf(spec: FixtureSuite['specs'][number]): string[] {
  const out: string[] = [];
  for (const block of (spec.spec.blocks ?? []) as Array<{ expect?: { tools?: unknown[] } }>) {
    for (const tool of (block.expect?.tools ?? []) as Array<{
      label?: string;
      input?: Record<string, unknown>;
    }>) {
      if (tool.label !== 'Read') continue;
      const path = tool.input?.file_path as { contains?: string; equals?: string } | string | undefined;
      const value = typeof path === 'string' ? path : (path?.contains ?? path?.equals);
      if (typeof value === 'string' && value !== '') out.push(value);
    }
  }
  return out;
}

let fixtureFiles: string[] | undefined;
function filesOfFixture(): string[] {
  fixtureFiles ??= (
    readdirSync(FIXTURE, { recursive: true, withFileTypes: true }) as Array<{
      isFile(): boolean;
      parentPath: string;
      name: string;
    }>
  )
    .filter((entry) => entry.isFile())
    .map((entry) => relative(FIXTURE, join(entry.parentPath, entry.name)));
  return fixtureFiles;
}

function seedFreeFamily(
  id: string,
  level: number,
  component: string,
  specs: Array<{
    key: string;
    tier: Tier;
    title: string;
    cause: string;
    component?: string;
    judge(suite: FixtureSuite): Promise<ItemResult> | ItemResult;
  }>,
): Family {
  const items = itemsOf(
    id,
    level,
    component,
    specs.map(({ key, tier, title, cause, component: own }) => ({
      key,
      tier,
      title,
      cause,
      ...(own ? { component: own } : {}),
    })),
  );
  return {
    id,
    level,
    component,
    items,
    seedFree: true,
    async evaluate() {
      const suite = await fixtureSuite();
      const out = new Map<string, ItemResult>();
      for (const spec of specs) {
        try {
          out.set(`${id}.${spec.key}`, await spec.judge(suite));
        } catch (cause) {
          out.set(`${id}.${spec.key}`, {
            pass: false,
            detail: `the item threw: ${cause instanceof Error ? cause.message : String(cause)}`,
          });
        }
      }
      return out;
    },
  };
}

const ofType = (suite: FixtureSuite, type: string) =>
  suite.specs.filter((spec) => spec.complete && spec.testType === type);

/** The most specs a failure detail lists by id and ask; the rest are counted. */
const LISTED = 50;

/** What the fake sets off for an ask: the ids of the atoms, from its own dispatch over the generated grammar. */
type FakeDispatch = (ask: string) => string[];

const dispatchOf = new WeakMap<FixtureSuite, Promise<FakeDispatch>>();

/**
 * The fake's dispatch for a suite: the approved map and the phrase bank beside it, and the grammar generated by
 * code from that map, written to a folder of its own.
 */
function fakeDispatch(suite: FixtureSuite): Promise<FakeDispatch> {
  let found = dispatchOf.get(suite);
  if (!found) {
    found = (async () => {
      const map = await loadEstateMap(suite.map);
      if (!map.ok) throw new Error('the map does not load');
      const folder = mkdtempSync(join(tmpdir(), 'estate-ask-grammar-'));
      const grammar = join(folder, 'grammar.json');
      writeFileSync(grammar, JSON.stringify(askGrammar(map.map.atoms as unknown as MapAtom[])));
      const beside = join(suite.work, 'phrases.yaml');
      const phrases = existsSync(beside) ? beside : join(FIXTURE, 'phrases.yaml');
      const fake = (await import(pathToFileURL(join(FIXTURE, 'live/fake/dispatch.mjs')).href)) as {
        loadDispatch(env: Record<string, string>): unknown;
        setOff(index: unknown, ask: string): { atoms: Array<{ id: string }> };
      };
      const index = fake.loadDispatch({ FAKE_MAP: suite.map, FAKE_PHRASES: phrases, FAKE_GRAMMAR: grammar });
      return (ask: string) => fake.setOff(index, ask).atoms.map((atom) => atom.id);
    })();
    dispatchOf.set(suite, found);
  }
  return found;
}

/** The situations of the phrase bank beside the suite: their use and the atoms they set off, by id. */
function situationsOf(suite: FixtureSuite): Map<string, { use: string; atoms: string[] }> {
  const beside = join(suite.work, 'phrases.yaml');
  const bank = parse(readFileSync(existsSync(beside) ? beside : join(FIXTURE, 'phrases.yaml'), 'utf8')) as {
    situations?: Array<{ id?: string; use?: string; atoms?: string[] }>;
  };
  return new Map(
    (bank.situations ?? []).map((situation) => [
      String(situation.id),
      { use: String(situation.use), atoms: situation.atoms ?? [] },
    ]),
  );
}

/**
 * The act a spec carries: the atom `askFrom` names for a code-written ask, the atoms of its situation for a bank
 * phrase or a recorded session. An empty list for an ask that carries none (a neutral ask, a situation just
 * outside the trigger or a near miss); undefined when the spec carries no readable act at all.
 */
function carriedAct(
  spec: FixtureSuite['specs'][number],
  situations: ReadonlyMap<string, { use: string; atoms: string[] }>,
): string[] | undefined {
  type Meta = { ask?: unknown; askFrom?: unknown; situation?: unknown };
  const meta = (spec.spec.metadata?.estate ?? {}) as Meta;
  if (meta.ask === 'code') {
    if (typeof meta.askFrom !== 'string' || meta.askFrom === '') return undefined;
    if (meta.askFrom === 'neutral') return [];
    return [meta.askFrom.split(' ')[0] as string];
  }
  const situation = typeof meta.situation === 'string' ? situations.get(meta.situation) : undefined;
  if (!situation) return undefined;
  return situation.use === 'outside' || situation.use === 'near_miss' ? [] : situation.atoms;
}

export function taskFamily(): Family {
  return seedFreeFamily(
    'gen.task',
    4,
    GENERATE,
    TEST_TYPES.map((type) => ({
      key: type,
      tier: 2 as Tier,
      title: `the first ask of every complete ${type} spec sets off, in the fake agent, the act the spec carries`,
      cause: 'ask for the act of the row, in a text the fake sets off for that act and no other',
      async judge(suite) {
        const specs = ofType(suite, type);
        if (specs.length === 0) return { pass: false, detail: `no complete ${type} spec` };
        const map = await loadEstateMap(suite.map);
        if (!map.ok) return { pass: false, detail: 'the map does not load' };
        const known = new Set(map.map.atoms.map((atom) => atom.id));
        const setOff = await fakeDispatch(suite);
        const situations = situationsOf(suite);
        const bad: Array<[FixtureSuite['specs'][number], string]> = [];
        for (const spec of specs) {
          const ask = firstAsk(spec) ?? '';
          const act = carriedAct(spec, situations);
          const fired = setOff(ask);
          if (act === undefined) bad.push([spec, 'it carries no act']);
          else if (act.length === 0) {
            const row = fired.filter((id) => spec.atoms.includes(id));
            if (row.length > 0) bad.push([spec, `it carries no act and sets off ${row[0]}`]);
          } else if (act.some((id) => !known.has(id)))
            bad.push([spec, `its act ${act[0]} is no atom of the map`]);
          else if (!act.some((id) => fired.includes(id)))
            bad.push([spec, `the fake does not set off its act ${act[0]}`]);
        }
        return bad.length === 0
          ? { pass: true, detail: `holds (${specs.length})` }
          : {
              pass: false,
              detail: `${bad.length} of ${specs.length} asks do not set off their act: ${bad
                .slice(0, LISTED)
                .map(([spec, why]) => `${spec.id} ("${firstAsk(spec)}": ${why})`)
                .join('; ')}${bad.length > LISTED ? `; and ${bad.length - LISTED} more` : ''}`,
            };
      },
    })),
  );
}

export function readsFamily(): Family {
  return seedFreeFamily(
    'gen.reads',
    4,
    THEN,
    TEST_TYPES.map((type) => ({
      key: type,
      tier: 2 as Tier,
      title: `no complete ${type} spec expects a Read of a file the estate lacks`,
      cause: 'expect a Read only of a file the estate holds',
      judge(suite) {
        const files = filesOfFixture();
        const specs = ofType(suite, type);
        if (specs.length === 0) return { pass: false, detail: `no complete ${type} spec` };
        for (const spec of specs) {
          for (const read of readsOf(spec)) {
            const clean = read.replace(/^\.\//, '');
            if (!existsSync(join(FIXTURE, clean)) && !files.some((file) => file.endsWith(clean)))
              return { pass: false, detail: `${spec.id} expects a Read of ${read}, which the estate lacks` };
          }
        }
        return { pass: true, detail: `holds (${specs.length})` };
      },
    })),
  );
}

const FOCUS_KINDS: Array<[string, Tier]> = [
  ['instruction', 2],
  ['gate', 2],
  ['reference', 3],
  ['route', 1],
  ['skill', 2],
  ['script', 3],
  ['subagent', 3],
  ['guard', 3],
  ['tool', 3],
  ['register', 3],
  ['stage', 3],
  ['hazard', 4],
  ['setting', 4],
  ['invariant', 4],
];
/** docs/estate.md section 5 (--focus): the report names the atoms with no complete spec. */
const AT_LEAST = 1;
const SKILLS = ['invoice-reconcile', 'shipment-tracker', 'supplier-email', 'weekly-report', 'standing'];
/** The gap markers and their fix; a fix the generated estates' items already name keeps that cause. */
const MARKERS: Array<[string, string]> = [
  ['needs-ordered-anchor', 'anchor an ordered pair whose ends are no tool label, skill or stage'],
  ['needs-stage-reach-check', 'write a stage reach check'],
  ['needs-guard-timing', 'write a guard timing check'],
  ['needs-guard-message-check', 'write a guard message check'],
  ['needs-recorded-session', 'replay a row from a recorded session the generator finds by itself'],
  ['needs-negation', 'write the inverse of a predicate for a negative control'],
];

export function coverageFamily(): Family {
  return seedFreeFamily('gen.coverage', 4, GENERATE, [
    ...FOCUS_KINDS.map(([kind, tier]) => ({
      key: `one-per-${kind}`,
      tier,
      title: `every ${kind} atom is named by at least ${AT_LEAST} complete spec`,
      cause: `generate a complete spec for every ${kind} atom`,
      async judge(suite: FixtureSuite): Promise<ItemResult> {
        const map = await loadEstateMap(suite.map);
        if (!map.ok) return { pass: false, detail: 'the map does not load' };
        const atoms = map.map.atoms.filter((atom) => atom.kind === kind);
        if (atoms.length === 0) return { pass: false, detail: `the fixture holds no ${kind} atom` };
        // docs/estate.md section 5: a Read of a file the estate copy does not hold cannot succeed. With a registered
        // `some_call` checker the complete specs of that reference check the attempted Read of the exact file with
        // it, never a successful read; with no such checker the reference waits on `needs-existing-file`.
        const waiting = new Set(
          (suite.report.gaps ?? []).find((entry) => entry.marker === 'needs-existing-file')?.atoms ?? [],
        );
        const absent = atoms.filter((atom) => kind === 'reference' && atom.fields?.exists === false);
        if (!suite.checks.includes('some_call')) {
          const unmarked = absent.filter((atom) => !waiting.has(atom.id));
          if (unmarked.length > 0)
            return {
              pass: false,
              detail: `${unmarked.length} of ${absent.length} references to a missing file are not marked needs-existing-file, such as ${unmarked[0]?.id}`,
            };
        } else {
          const unchecked = absent.filter((atom) => {
            const path = String(atom.fields?.path ?? '');
            if (path === '' || waiting.has(atom.id)) return true;
            const name = path.slice(path.lastIndexOf('/') + 1);
            const specs = suite.specs.filter((spec) => spec.complete && spec.atoms.includes(atom.id));
            const attempts = (spec: (typeof specs)[number]) =>
              (
                ((spec.spec.rules?.custom?.some_call as { calls?: unknown } | undefined)?.calls ??
                  []) as Array<{
                  label?: unknown;
                  input?: { file_path?: { contains?: unknown } };
                  count?: unknown;
                }>
              ).filter((call) => call.label === 'Read' && call.input?.file_path?.contains === path);
            const reads = (spec: (typeof specs)[number]) =>
              (spec.spec.blocks ?? [])
                .flatMap((block) => block.expect?.references ?? [])
                .some((ref) => String((ref as { path?: unknown }).path ?? '').includes(name));
            return (
              specs.length === 0 ||
              !specs.every((spec) => attempts(spec).length > 0 && !reads(spec)) ||
              !specs.some((spec) =>
                attempts(spec).some((call) => {
                  const min = (call.count as { min?: unknown } | undefined)?.min;
                  return typeof min === 'number' && min >= 1;
                }),
              )
            );
          });
          if (unchecked.length > 0)
            return {
              pass: false,
              detail: `${unchecked.length} of ${absent.length} references to a missing file have no complete spec that checks the attempted Read with some_call, such as ${unchecked[0]?.id}`,
            };
        }
        const short = atoms
          .filter((atom) => !absent.includes(atom))
          .map(
            (atom) =>
              [
                atom.id,
                suite.specs.filter((spec) => spec.complete && spec.atoms.includes(atom.id)).length,
              ] as const,
          )
          .filter(([, count]) => count < AT_LEAST);
        return short.length === 0
          ? { pass: true, detail: 'holds' }
          : {
              pass: false,
              detail: `${short.length} of ${atoms.length} ${kind} atoms have fewer than ${AT_LEAST} complete specs, such as ${short[0]?.[0]} with ${short[0]?.[1]}`,
            };
      },
    })),
    ...SKILLS.map((skill) => ({
      key: `judged-${skill}`,
      tier: 3 as Tier,
      title: `every domain rule of ${skill} has a judged criterion in a complete spec`,
      cause: 'judge every domain rule no code checks with a criterion from its own words',
      component: THEN,
      async judge(suite: FixtureSuite): Promise<ItemResult> {
        const map = await loadEstateMap(suite.map);
        if (!map.ok) return { pass: false, detail: 'the map does not load' };
        const rules = map.map.atoms.filter(
          (atom) =>
            atom.kind === 'instruction' &&
            atom.id.startsWith(`instruction.${skill}.`) &&
            atom.evidence.some((item) => item.type === 'custom'),
        );
        if (rules.length === 0) return { pass: true, detail: 'no domain rule here' };
        const unjudged = rules.filter(
          (rule) =>
            !suite.specs.some(
              (spec) =>
                spec.complete &&
                ((spec.spec.blocks ?? []) as Array<{ expect?: { criteria?: unknown[] } }>).some((block) =>
                  (block.expect?.criteria ?? []).some((criterion) =>
                    JSON.stringify(criterion).includes(rule.id),
                  ),
                ),
            ),
        );
        return unjudged.length === 0
          ? { pass: true, detail: `holds (${rules.length})` }
          : {
              pass: false,
              detail: `${unjudged.length} of ${rules.length} domain rules have no judged criterion, such as ${unjudged[0]?.id}`,
            };
      },
    })),
    ...MARKERS.map(([marker, cause]) => ({
      key: marker,
      tier: 4 as Tier,
      title: `no generated spec of the fixture is incomplete for ${marker}`,
      cause,
      component: THEN,
      judge(suite: FixtureSuite): ItemResult {
        const gap = (suite.report.gaps ?? []).find((entry) => entry.marker === marker);
        return !gap || gap.specs === 0
          ? { pass: true, detail: 'holds' }
          : {
              pass: false,
              detail: `${gap.specs} specs are incomplete for ${marker}, such as on ${gap.atoms[0]}`,
            };
      },
    })),
  ]);
}
