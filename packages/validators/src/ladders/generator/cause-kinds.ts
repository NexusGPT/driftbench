const causes = new Map<string, string>();
for (const kind of GENERATOR_CAUSE_KINDS) {
  for (const id of kind.items) {
    if (causes.has(id)) throw new Error(`Duplicate generator cause assignment: ${id}`);
    causes.set(id, kind.cause);
  }
}

export function authoredCauseFor(id: string): string {
  const cause = causes.get(id);
  if (!cause) throw new Error(`Generator item needs an authored cause: ${id}`);
  return cause;
}
