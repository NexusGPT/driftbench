import assert from 'node:assert/strict';
import { responsesBody, solCost, claudeConfig } from './frontier';
const body=responsesBody({system:'judge',user:'compare'},{type:'object'});
assert.equal(body.max_output_tokens,4096);
assert.equal(body.reasoning.effort,'medium');
assert.equal(body.service_tier,'default');
assert.equal('temperature' in body,false);
assert.equal(body.text?.format.strict,true);
assert.equal(body.instructions,'judge');
assert.equal(body.input,'compare');
assert.equal(solCost({input_tokens:1000,input_tokens_details:{cached_tokens:200},output_tokens:100}),.00262);
assert.throws(()=>solCost({input_tokens:1000}));
const {args,env}=claudeConfig({system:'frozen prompt'},'/empty');
assert.equal(env.CLAUDE_CODE_MAX_OUTPUT_TOKENS,'4096');
assert.equal(env.CLAUDE_CODE_MAX_RETRIES,'0');
assert.equal('OPENAI_API_KEY' in env,false);
assert.equal(args[args.indexOf('--model')+1],'sonnet');
assert.equal(args[args.indexOf('--tools')+1],'');
assert.equal(args[args.indexOf('--setting-sources')+1],'');
assert.equal(args[args.indexOf('--system-prompt')+1],'frozen prompt');
console.log('Focused provider shape, cost, isolation and token-cap checks pass. No paid calls.');
