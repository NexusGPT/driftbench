import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, writeFile, appendFile } from 'node:fs/promises';
import { contestantById } from '../../src/contestants.ts';
import { loadBenchmark, splitOf } from '../../src/data.ts';
import { runBenchmark } from '../../src/run.ts';
import { scorePoints } from '../../src/score.ts';
import { testSample, testMetrics } from '../../src/verify-test-metrics.ts';
const folder = 'examples/judge-benchmarks/results/verify-dev';
const save = (name,value,options) => writeFile(`${folder}/${name}.json`,JSON.stringify(value,null,2)+'\n',options);
const freeze = JSON.parse(await readFile(`${folder}/freeze.json`,'utf8'));
for (const [path,expected] of Object.entries(freeze.hashes)) {
 if (createHash('sha256').update(await readFile(path)).digest('hex') !== expected) throw Error(`Frozen artifact changed: ${path}`);
}
execFileSync('git',['merge-base','--is-ancestor',freeze.sha,'HEAD']);
const benchmark = await loadBenchmark('longjudge-verify');
const population = benchmark.items.filter(x=>splitOf('longjudge-verify',x.id)==='test');
if (createHash('sha256').update(JSON.stringify(population)).digest('hex') !== freeze.populationHash) throw Error('Population changed');
const audit = JSON.parse(await readFile(`${folder}/test-label-audit.json`,'utf8'));
const proved = audit.items.filter(x=>x.verdict==='proved_conflict');
const corrections = new Map(proved.map(x=>[x.id,x.audited_correct]));
const strict = new Map(proved.filter(x=>x.proof_class==='literal_premises').map(x=>[x.id,x.audited_correct]));
if (corrections.size!==23 || strict.size!==22) throw Error('Audit changed');
const recording='examples/judge-benchmarks/recordings/longjudge-verify/haiku.jsonl';
const baseline=execFileSync('git',['show',`0fa48a41:${recording}`],{encoding:'utf8',maxBuffer:64*1024*1024}).trimEnd().split('\n').length;
const spent=async()=> (await readFile(recording,'utf8')).trimEnd().split('\n').slice(baseline).reduce((s,l)=>s+Number(JSON.parse(l).costUsd??0),0);
const deadlineAt=Date.parse('2026-10-13T06:30:00+02:00');
const before=await spent();
if (Date.now()>=deadlineAt || before>=7.97) throw Error('Budget/deadline reached');
const pilot=testSample(population,20);
if (JSON.stringify(pilot.map(x=>x.id))!==JSON.stringify(freeze.pilotIds)) throw Error('Pilot changed');
await save('test-started',{at:new Date().toISOString(),freeze:freeze.sha,before,pilotIds:freeze.pilotIds},{flag:'wx'});
const run=async(items)=>runBenchmark({bench:'longjudge-verify',model:'haiku',contestants:[contestantById(freeze.contestant)],items,criterion:benchmark.criterion,split:'all',concurrency:1,capUsd:7.97-await spent(),deadlineAt,includeDecisions:true});
const start=Date.now();
console.log(JSON.stringify({event:'pilot-start',at:new Date().toISOString(),items:20,freeze:freeze.sha}));
const first=await run(pilot);
const pilotSeconds=(Date.now()-start)/1000;
await save('test-pilot',first);
const perItem=pilotSeconds/20;
const remainingSeconds=Math.max(0,(deadlineAt-Date.now())/1000-300);
const fullFits=!first.stopped && perItem*201<=remainingSeconds && (first.newSpendUsd/20)*201*1.5<=7.97-await spent();
const affordable=Math.floor((7.97-await spent())/Math.max(first.newSpendUsd/20*1.5,0.00001));
let size=fullFits?221:Math.min(221,20+Math.floor(remainingSeconds/(perItem*1.35)),20+affordable);
size=Math.max(20,size);
let selected;
for (;size>=20;size--) {
 selected=testSample(population,size);
 if (pilot.every(p=>selected.some(x=>x.id===p.id))) break;
}
const selection={freeze:freeze.sha,at:new Date().toISOString(),pilotSeconds,secondsPerItem:perItem,projectedFullSeconds:perItem*221,remainingSeconds,fullFits,size,selectedIds:selected.map(x=>x.id),policy:freeze.throughputPolicy};
await save('test-selection',selection);
console.log(JSON.stringify({event:'pilot-measured',...selection,selectedIds:undefined}));
let second;
if (!first.stopped && size>20) second=await run(selected.filter(x=>!freeze.pilotIds.includes(x.id)));
if(second) await save('test-remainder',second);
const parts=[first,...(second?[second]:[])];
const cs=parts.map(x=>x.contestants[0]);
const decisions=cs.flatMap(x=>x.decisions??[]);
if(new Set(decisions.map(x=>x.id)).size!==decisions.length) throw Error('Repeated TEST item');
const byId=new Map(population.map(x=>[x.id,x]));
const costUsd=cs.reduce((s,x)=>s+x.costUsd,0);
const officialSummary=scorePoints(decisions.map(d=>({item:byId.get(d.id),decision:d,missing:d.missing})));
const result={bench:'longjudge-verify',model:'haiku',items:decisions.length,newSpendUsd:parts.reduce((s,x)=>s+x.newSpendUsd,0),newCalls:parts.reduce((s,x)=>s+x.newCalls,0),replayed:parts.reduce((s,x)=>s+x.replayed,0),failedCalls:parts.reduce((s,x)=>s+x.failedCalls,0),stopped:parts.find(x=>x.stopped)?.stopped,contestants:[{contestant:freeze.contestant,mode:'pointwise',summary:officialSummary,costUsd,calls:cs.reduce((s,x)=>s+x.calls,0),decisions}]};
await save('test-result',result);
const metrics={freeze:freeze.sha,contestant:freeze.contestant,population:221,selected:size,selectedInReport:decisions.length,judgmentsReturned:decisions.filter(x=>!x.missing).length,binaryVerdicts:decisions.filter(x=>x.pass!==undefined).length,stopped:result.stopped,official:testMetrics(population,decisions,new Map()),audited:testMetrics(population,decisions,corrections),strictAudited:testMetrics(population,decisions,strict),auditCorrectionsInSample:selected.filter(x=>corrections.has(x.id)).length,costPer100Usd:costUsd*100/decisions.length,newSpendUsd:result.newSpendUsd,taskRecordedSpendUsd:await spent(),pilotSeconds,elapsedSeconds:(Date.now()-start)/1000,partialCaveat:result.stopped?'Ordered incomplete sample: population intervals are not valid.':undefined};
await save('test-metrics',metrics);
console.log(JSON.stringify({event:'test-complete',...metrics},null,2));
if(process.env.VERIFY_SPEND_LEDGER) await appendFile(process.env.VERIFY_SPEND_LEDGER,`| ${new Date().toLocaleTimeString('en-GB',{timeZone:'Europe/Brussels',hour:'2-digit',minute:'2-digit'})} | codex/verify-judge single frozen TEST, ${decisions.length}/${size} of 221; official ${(metrics.official.sampleAccuracy*100).toFixed(1)}, audited ${(metrics.audited.sampleAccuracy*100).toFixed(1)} | haiku | ${result.newCalls} | remaining task cap | ${result.newSpendUsd.toFixed(7)} | task ${metrics.taskRecordedSpendUsd.toFixed(7)} of 8 |\n`);
