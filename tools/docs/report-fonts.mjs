// Writes packages/report/src/fonts.ts: the four faces of the scorecard page as base64 woff2, so the page
// stays one file with no external asset. The faces are under the SIL Open Font License, packages/report/fonts/OFL.txt.
//   node tools/docs/report-fonts.mjs <folder with the woff2 files>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) {
  process.stderr.write('Give the folder that holds the woff2 files.\n');
  process.exit(2);
}
const faces = [
  ['GEIST', 'Geist-latin.woff2'],
  ['GEIST_MONO', 'GeistMono-latin.woff2'],
  ['CASLON_DISPLAY', 'LibreCaslonDisplay-400-latin.woff2'],
  ['CASLON_TEXT', 'LibreCaslonText-400-latin.woff2'],
];
const lines = [
  '// Generated by tools/docs/report-fonts.mjs. The Latin subsets of Geist, Geist Mono, Libre Caslon Display and',
  '// Libre Caslon Text, as base64 woff2, under the SIL Open Font License 1.1: packages/report/fonts/OFL.txt.',
];
for (const [name, file] of faces) {
  lines.push(`export const ${name} = '${readFileSync(join(dir, file)).toString('base64')}';`);
}
writeFileSync(new URL('../../packages/report/src/fonts.ts', import.meta.url), `${lines.join('\n')}\n`);
process.stdout.write('Wrote packages/report/src/fonts.ts\n');
